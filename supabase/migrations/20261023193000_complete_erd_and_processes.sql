-- 3. 상담창구일정슬롯 (consult_slot) - 물리 ERD 테이블 #7 (프로세스 02, 04, 07)
create table if not exists public.consult_slot (
  id uuid primary key default gen_random_uuid(),
  org_code text not null default 'ORG-HB-01',
  dept_code text not null default 'D01' references public.department_info(dept_code) on delete cascade,
  slot_date date not null default current_date,
  start_time text not null,
  end_time text not null,
  max_capacity integer not null default 5 check (max_capacity > 0),
  booked_count integer not null default 0 check (booked_count >= 0),
  is_closed boolean not null default false,
  unique (dept_code, slot_date, start_time)
);
alter table public.consult_slot enable row level security;
revoke all on public.consult_slot from anon, authenticated;
grant select on public.consult_slot to anon, authenticated;
drop policy if exists slot_public_read on public.consult_slot;
