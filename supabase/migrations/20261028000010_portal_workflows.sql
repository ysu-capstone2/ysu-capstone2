begin;

-- Preserve legacy knowledge; a clean project starts with an empty maintained KB.
create table if not exists public.admin_knowledge (
 id bigint generated by default as identity primary key,
 title text not null,
 content text not null,
 category_code text not null default '일반행정',
 required_docs text not null default '',
 fee text not null default '',
 keywords text[] not null default '{}'
);
create table if not exists public.department_info (
 dept_code text primary key,
 dept_name text not null,
 dept_tel text not null default ''
);
alter table public.admin_knowledge enable row level security;
alter table public.department_info enable row level security;
-- Preserve the public-reference and administrator policies from the ERD migration.
grant select on public.admin_knowledge, public.department_info to anon, authenticated;
grant select on public.admin_knowledge, public.department_info to service_role;
-- Keep administrator writes without evaluating a second SELECT policy.
drop policy if exists knowledge_admin_write on public.admin_knowledge;
create policy knowledge_admin_insert on public.admin_knowledge for insert to authenticated
 with check (((select auth.jwt())->'app_metadata'->>'role')='admin');
create policy knowledge_admin_update on public.admin_knowledge for update to authenticated
 using (((select auth.jwt())->'app_metadata'->>'role')='admin')
 with check (((select auth.jwt())->'app_metadata'->>'role')='admin');

alter table public.citizen_complaints add column preferred_at timestamptz;
alter table public.citizen_complaints add column supplements jsonb not null default '[]'::jsonb
 check (jsonb_typeof(supplements) = 'array' and jsonb_array_length(supplements) <= 20);
alter table public.citizen_complaints drop constraint citizen_complaints_process_status_check;
alter table public.citizen_complaints add constraint citizen_complaints_process_status_check
 check (process_status in ('접수','처리중','완료','보완요청','취소'));
grant insert (preferred_at) on public.citizen_complaints to authenticated;

-- The server supplies the verified user ID. No client/user role can call this RPC.
-- Locking the receipt serializes owner actions with administrator updates.
create function public.portal_member_complaint(p_id uuid,p_user uuid,p_action text,p_text text default '',p_preferred timestamptz default null)
 returns jsonb language plpgsql security invoker set search_path='' as $$
declare c public.citizen_complaints;
begin
 select * into c from public.citizen_complaints where id=p_id and user_id=p_user for update;
 if not found then return jsonb_build_object('ok',false,'reason','not_found'); end if;
 if p_action='cancel' and c.process_status='취소' then return jsonb_build_object('ok',true); end if;
 if p_action='supplement' then
  if c.process_status<>'보완요청' or char_length(trim(coalesce(p_text,''))) not between 1 and 2000 or jsonb_array_length(c.supplements)>=20 then
   return jsonb_build_object('ok',false,'reason','invalid_state');
  end if;
  update public.citizen_complaints set supplements=supplements || jsonb_build_array(jsonb_build_object('text',trim(p_text),'submittedAt',now())),process_status='처리중',updated_at=now() where id=p_id;
 elsif p_action='reschedule' then
  if c.process_status not in ('접수','보완요청') or p_preferred is null or p_preferred<=now() or p_preferred>now()+interval '90 days' then
   return jsonb_build_object('ok',false,'reason','invalid_state');
  end if;
  update public.citizen_complaints set preferred_at=p_preferred,updated_at=now() where id=p_id;
 elsif p_action='cancel' then
  if c.process_status not in ('접수','보완요청') then return jsonb_build_object('ok',false,'reason','invalid_state'); end if;
  update public.citizen_complaints set process_status='취소',updated_at=now() where id=p_id;
 else
  return jsonb_build_object('ok',false,'reason','invalid_action');
 end if;
 return jsonb_build_object('ok',true);
end $$;
revoke all on function public.portal_member_complaint(uuid,uuid,text,text,timestamptz) from public,anon,authenticated;
grant execute on function public.portal_member_complaint(uuid,uuid,text,text,timestamptz) to service_role;

create or replace function public.portal_summary() returns jsonb language plpgsql security invoker set search_path='' as $$
begin
 if coalesce((select auth.jwt()->'app_metadata'->>'role'),'') <> 'admin' then raise insufficient_privilege; end if;
 return jsonb_build_object(
  'totalComplaints',(select count(*) from public.citizen_complaints),
  'pending',(select count(*) from public.citizen_complaints where process_status='접수'),
  'processing',(select count(*) from public.citizen_complaints where process_status in ('처리중','보완요청')),
  'completed',(select count(*) from public.citizen_complaints where process_status='완료'),
  'cancelled',(select count(*) from public.citizen_complaints where process_status='취소'),
  'totalInquiries',(select count(*) from public.chat_session),
  'waiting',(select coalesce(sum(waiting_count),0) from public.service_counters));
end $$;
commit;
